interface Props {
    name?: string;
    className?: string;
}

export default function NavIcon({ name, className = 'size-3.5' }: Props) {
    if (!name) {
        return null;
    }

    const Icon = NAV_ICONS[name as keyof typeof NAV_ICONS];
    if (!Icon) {
        return null;
    }

    return <Icon className={className} strokeWidth={1.8} aria-hidden="true" />;
}
